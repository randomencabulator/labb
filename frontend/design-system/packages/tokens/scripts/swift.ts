// The tokens for iOS: an asset catalog (a colour set per system colour, with light and dark, and per
// palette step) and Tokens.swift (everything else), for the LabbDesign Swift package in ../../swift.
// build.ts resolves the tokens and calls swiftFiles(); this only turns them into files.

export type SwiftColor = { components: number[]; alpha: number };
export type SwiftInput = {
  system: { name: string; use: string; light: SwiftColor; dark: SwiftColor }[];
  palette: { name: string; color: SwiftColor }[]; // "sand-500", "white"
  brand: { name: string; ref: string }[]; // "yellow" → "yellow-300"
  space: { key: string; px: number }[];
  radius: { key: string; px: number; use: string }[];
  text: { key: string; size: number; line: number; use: string }[];
  weight: { key: string; value: number }[];
  tracking: { key: string; em: number; use: string }[];
  family: { key: string; names: string[] }[];
  shadow: { key: string; x: number; y: number; blur: number; spread: number; color: { system: string } | { literal: SwiftColor }; inset: boolean; use: string }[];
  motion: { key: string; ms: number; curve: number[]; use: string }[];
  border: { key: string; px: number }[];
  z: { key: string; value: number }[];
};

// Paths inside the Swift package's target folder (Sources/LabbDesign)
export const SWIFT_GENERATED = ["Generated", "Resources/LabbColors.xcassets"];

const HEADER = "// Generated by frontend/design-system/packages/tokens/scripts/build.ts from tokens/*.json. Don't edit; edit the JSON.";
const XCODE_INFO = { author: "xcode", version: 1 };
const json = (v: unknown) => JSON.stringify(v, null, 2) + "\n";

// "accent-fill" → accentFill, "series-1" → series1, "2xl" → xxl, "6" → s6
function ident(name: string, numberPrefix = "") {
  const lead = /^(\d+)x(.*)$/.exec(name);
  if (lead) name = "x".repeat(Number(lead[1])) + lead[2];
  const camel = name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  return /^\d/.test(camel) ? numberPrefix + camel : camel;
}

const num = (n: number) => (Number.isInteger(n) ? String(n) : String(Math.round(n * 10000) / 10000));
const doc = (text: string, indent = "    ") => (text ? `${indent}/// ${text}\n` : "");

// An asset catalog colour: exact 8-bit sRGB, like the CSS
function assetColor(c: SwiftColor) {
  const hex = (x: number) => "0x" + Math.round(x * 255).toString(16).toUpperCase().padStart(2, "0");
  return {
    "color-space": "srgb",
    // Alpha is always written with a decimal point ("1.000"): beside 8-bit components, Xcode reads "1"
    // as 1 out of 255, all but invisible
    components: { red: hex(c.components[0]), green: hex(c.components[1]), blue: hex(c.components[2]), alpha: c.alpha.toFixed(3) },
  };
}

const swiftColor = (c: SwiftColor) =>
  `Color(.sRGB, red: ${num(c.components[0])}, green: ${num(c.components[1])}, blue: ${num(c.components[2])}, opacity: ${num(c.alpha)})`;

// The Apple text style each size scales with under Dynamic Type
function textStyle(size: number) {
  if (size <= 11) return "caption2";
  if (size <= 12) return "caption";
  if (size <= 13) return "footnote";
  if (size <= 15) return "subheadline";
  if (size <= 17) return "body";
  if (size <= 20) return "title3";
  if (size <= 24) return "title2";
  if (size <= 29) return "title";
  return "largeTitle";
}

const WEIGHTS: Record<number, string> = { 100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium", 600: "semibold", 700: "bold", 800: "heavy", 900: "black" };

export function swiftFiles(t: SwiftInput): Record<string, string> {
  const files: Record<string, string> = {};
  const cat = "Resources/LabbColors.xcassets";
  files[`${cat}/Contents.json`] = json({ info: XCODE_INFO });
  // Folders that namespace the colours: "sys/bg", "ref/sand-500"
  for (const folder of ["sys", "ref"]) files[`${cat}/${folder}/Contents.json`] = json({ info: XCODE_INFO, properties: { "provides-namespace": true } });
  for (const c of t.system) {
    files[`${cat}/sys/${c.name}.colorset/Contents.json`] = json({
      colors: [
        { color: assetColor(c.light), idiom: "universal" },
        { appearances: [{ appearance: "luminosity", value: "dark" }], color: assetColor(c.dark), idiom: "universal" },
      ],
      info: XCODE_INFO,
    });
  }
  for (const c of t.palette) {
    files[`${cat}/ref/${c.name}.colorset/Contents.json`] = json({ colors: [{ color: assetColor(c.color), idiom: "universal" }], info: XCODE_INFO });
  }

  const weightName = (v: number) => WEIGHTS[v] ?? (() => { throw new Error(`no SwiftUI weight for ${v}`); })();
  const swift = `${HEADER}
import SwiftUI

// MARK: - Colours

/// System colours: what a colour is for. They come from the asset catalog with a light and a dark
/// value, so they follow the system's appearance. Use these, never the palette.
public struct LabbSystemColors: Sendable {
${t.system.map((c) => `${doc(c.use)}    public var ${ident(c.name)}: Color { Color("sys/${c.name}", bundle: .module) }`).join("\n")}
}

/// Reference colours: the palette, with no meaning attached. System colours point at these; views don't use them.
public struct LabbPalette: Sendable {
${t.palette.map((c) => `    public var ${ident(c.name)}: Color { Color("ref/${c.name}", bundle: .module) }`).join("\n")}
}

/// The brand colours, the same in both appearances (the hazard stripes and the logo)
public struct LabbBrandColors: Sendable {
${t.brand.map((b) => `    public var ${ident(b.name)}: Color { Color("ref/${b.ref}", bundle: .module) }`).join("\n")}
}

public extension ShapeStyle where Self == Color {
    /// labb's system colours: \`.foregroundStyle(.labb.text)\`, \`Color.labb.bg\`
    static var labb: LabbSystemColors { LabbSystemColors() }
    /// The reference palette (for defining colours, not for views)
    static var labbPalette: LabbPalette { LabbPalette() }
    /// The brand colours
    static var labbBrand: LabbBrandColors { LabbBrandColors() }
}

// MARK: - Spacing, corners, borders, layers (points)

/// Spacing on a 2pt grid
public enum LabbSpace {
${t.space.map((s) => `    public static let ${ident(s.key, "s")}: CGFloat = ${num(s.px)}`).join("\n")}
}

/// Corners: small and square-ish
public enum LabbRadius {
${t.radius.map((r) => `${doc(r.use)}    public static let ${ident(r.key)}: CGFloat = ${num(r.px)}`).join("\n")}
}

/// Border widths
public enum LabbBorder {
${t.border.map((b) => `    public static let ${ident(b.key)}: CGFloat = ${num(b.px)}`).join("\n")}
}

/// Stacking order, for zIndex
public enum LabbLayer {
${t.z.map((z) => `    public static let ${ident(z.key)}: Double = ${num(z.value)}`).join("\n")}
}

// MARK: - Type

/// Text sizes, each with its line height (a multiple of the size) and the Apple text style it scales
/// with under Dynamic Type. Use with \`.labbText(_:)\`.
public enum LabbTextStyle: String, CaseIterable, Sendable {
${t.text.map((s) => `${doc(s.use)}    case ${ident(s.key)}`).join("\n")}

    /// The size in points, before Dynamic Type
    public var size: CGFloat {
        switch self {
${t.text.map((s) => `        case .${ident(s.key)}: ${num(s.size)}`).join("\n")}
        }
    }

    /// The line height, as a multiple of the size
    public var lineHeight: CGFloat {
        switch self {
${t.text.map((s) => `        case .${ident(s.key)}: ${num(s.line)}`).join("\n")}
        }
    }

    /// The text style it scales with
    public var relativeTo: Font.TextStyle {
        switch self {
${t.text.map((s) => `        case .${ident(s.key)}: .${textStyle(s.size)}`).join("\n")}
        }
    }
}

/// Font weights
public enum LabbWeight {
${t.weight.map((w) => `    public static let ${ident(w.key)}: Font.Weight = .${weightName(w.value)}`).join("\n")}
}

/// Letter spacing, in em (multiply by the size for points; \`.labbText\` does)
public enum LabbTracking {
${t.tracking.map((tr) => `${doc(tr.use)}    public static let ${ident(tr.key)}: CGFloat = ${num(tr.em)}`).join("\n")}
}

/// The font families, as SwiftUI designs: the system's own sans, and its mono
public enum LabbFontDesign {
${t.family.map((f) => `    public static let ${ident(f.key)}: Font.Design = ${f.names.some((n) => /mono/i.test(n)) ? ".monospaced" : ".default"}`).join("\n")}
}

// MARK: - Shadows and motion

/// A shadow: solid and offset, never blurred (except the soft ones). \`.labbShadow(_:)\` draws it.
public struct LabbShadow: Sendable {
    public let x: CGFloat
    public let y: CGFloat
    public let blur: CGFloat
    public let spread: CGFloat
    public let color: Color
    /// Drawn inside the shape's leading edge, like the yellow bar on what's open
    public let inset: Bool

${t.shadow
  .map(
    (s) =>
      `${doc(s.use)}    public static var ${ident(s.key)}: LabbShadow { LabbShadow(x: ${num(s.x)}, y: ${num(s.y)}, blur: ${num(s.blur)}, spread: ${num(s.spread)}, color: ${"system" in s.color ? `Color.labb.${ident(s.color.system)}` : swiftColor(s.color.literal)}, inset: ${s.inset}) }`,
  )
  .join("\n")}
}

/// Motion: quick and small. Skip it when \`accessibilityReduceMotion\` is on.
public enum LabbMotion {
${t.motion.map((m) => `${doc(m.use)}    public static var ${ident(m.key)}: Animation { .timingCurve(${m.curve.map(num).join(", ")}, duration: ${num(m.ms / 1000)}) }`).join("\n")}
}
`;
  files["Generated/Tokens.swift"] = swift;
  return files;
}
